// bundle2pdf v2 (2026-10-27, A16/A17 drafts): identical to tools/bundle2pdf.cjs (v1, frozen for A1-A15 bundles) except that
// inline code keeps runs of spaces (white-space:pre-wrap), the rendering defect logged in notebook §48. New bundles use v2.
// Renders a list of wiki markdown pages into one printable PDF (marked + mermaid from CDN, headless Chromium).
// usage: node wiki2pdf.cjs <wikiDir> <out.pdf> <title> <page.md>...
const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");

(async () => {
  const [dir, out, title, ...pages] = process.argv.slice(2);
  const docs = pages.map((p) => ({ p, md: fs.readFileSync(path.join(dir, p), "utf8") }));
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${title}</title>
<script src="https://cdn.jsdelivr.net/npm/marked@12.0.2/marked.min.js"></script>
<script src="https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"></script>
<style>
 body{font:11pt/1.5 -apple-system,Helvetica,Arial,sans-serif;color:#111;margin:0}
 h1{font-size:20pt;border-bottom:2px solid #FCB813;padding-bottom:4px} h2{font-size:15pt;margin-top:1.4em} h3{font-size:12.5pt}
 table{border-collapse:collapse;width:100%;font-size:9pt;margin:.6em 0} th,td{border:1px solid #ccc;padding:3px 5px;vertical-align:top;text-align:left} th{background:#f3f3f3}
 code{font:9pt Menlo,monospace;background:#f5f5f5;padding:0 2px;white-space:pre-wrap} pre{background:#f5f5f5;padding:8px;font-size:8.5pt;white-space:pre-wrap}
 .page{page-break-before:always} .page:first-of-type{page-break-before:avoid} .src{font:8pt Menlo,monospace;color:#888}
 .cover{height:90vh;display:flex;flex-direction:column;justify-content:center} .cover h1{font-size:28pt;border:0}
</style></head><body>
<section class="cover"><h1>${title}</h1><p>${process.env.COVER_NOTE || "Wiki pages generated by the FlowX.AI legacy transformation agent from AWS CardDemo (open source, Apache-2.0)."} CONTRACT.md is the input/output contract for the build.</p>
<p>Pages included:</p><ul>${pages.map((p) => `<li><code>${p}</code></li>`).join("")}</ul></section>
<div id="docs"></div>
<script>
 const DOCS=${JSON.stringify(docs)};
 const root=document.getElementById("docs");
 for(const d of DOCS){const s=document.createElement("section");s.className="page";
   s.innerHTML='<div class="src">'+d.p+'</div>'+marked.parse(d.md);root.appendChild(s);}
 document.querySelectorAll("pre code.language-mermaid").forEach(c=>{const div=document.createElement("div");div.className="mermaid";div.textContent=c.textContent;c.parentElement.replaceWith(div);});
 mermaid.initialize({startOnLoad:false,theme:"neutral"});
 mermaid.run().catch(()=>{}).finally(()=>{window.__ready=true});
</script></body></html>`;
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.setContent(html, { waitUntil: "networkidle" });
  await p.waitForFunction(() => window.__ready === true, null, { timeout: 60000 });
  await p.pdf({ path: out, format: "A4", margin: { top: "16mm", bottom: "16mm", left: "14mm", right: "14mm" }, printBackground: true });
  await b.close();
  console.log("wrote", out);
})();
