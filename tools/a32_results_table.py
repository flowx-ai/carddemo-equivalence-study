"""A32 per-program counts for the three FlowX Platform MCP builds, from the committed score files (no rescoring).
    python3 tools/a32_results_table.py > results/runs/full/A32_RESULTS.md
The post-hoc browser column (browser_fix11, FIX11=1) is labelled as such and decides nothing."""
import json, os, sys

O = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILDS = ["r1", "r2", "r3"]


def load(path, skip_to_brace=False):
    p = os.path.join(O, path)
    if not os.path.exists(p):
        return None
    t = open(p).read()
    return json.loads(t[t.index("{"):] if skip_to_brace else t)


S = {b: load(f"results/runs/full/zflx/{b}/score/summary.json") for b in BUILDS}
BS = {b: load(f"results/runs/full/zflx/{b}/batch_score.json", True) for b in BUILDS}
UI = {b: load(f"results/runs/full/zflx/{b}/browser/ui_check.json") for b in BUILDS}
UI11 = {b: load(f"results/runs/full/zflx/{b}/browser_fix11/ui_check.json") for b in BUILDS}


def e2e(b):
    d = os.path.join(O, f"results/runs/full/zflx/{b}/e2e")
    out = {}
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if f.endswith(".result.json"):
            r = json.load(open(os.path.join(d, f)))
            out[r["case"]] = r["outcome"]
    return out


def pct(e, u):
    return f"{e}/{u} ({100 * e / u:.1f}%)" if u else "0/0"


w = print
w("# A32 results: FlowX Platform MCP, full base application, 3 builds\n")
w("Generated by `tools/a32_results_table.py` from the committed score files. A match with legacy, not correctness. "
  "Units resting on R-CEE-PIC8 are in their own column and decide nothing.\n")

w("## Hypotheses (refuted if at least 2 of 3 builds fail)\n")
w("| | " + " | ".join(BUILDS) + " |\n|---|" + "---|" * len(BUILDS))
w("| HF1 screens reachable (not reachable or absent) | " + " | ".join(
    ", ".join(f"{k} ({v})" for k, v in S[b]["H_reachable"]["not_reachable_or_absent"].items()) or "none" for b in BUILDS) + " |")
w("| HF2 programs with no silent screen difference | " + " | ".join(
    f"{S[b]['H_core_screens']['programs_no_silent']} of {S[b]['H_core_screens']['programs_scored']}" for b in BUILDS) + " |")
w("| HF3 money files: silent units | " + " | ".join(
    f"{S[b]['H_money_files']['silent_units']} (+{S[b]['H_money_files']['silent_resting_on_pic8']} on R-CEE-PIC8)" for b in BUILDS) + " |")
w("| HF4 list paging units equal | " + " | ".join(pct(S[b]["H_list_paging"]["equal"], S[b]["H_list_paging"]["units"]) for b in BUILDS) + " |")
w("| HF5 browser steps ok / cases all ok (registered) | " + " | ".join(
    f"{UI[b]['steps_ok']}, {sum(UI[b]['cases_all_steps_ok'].values())} of {len(UI[b]['cases_all_steps_ok'])}" for b in BUILDS) + " |")
w("| HF6 end to end | " + " | ".join("; ".join(f"{k.replace('e2e-o2-', '')}: {v}" for k, v in e2e(b).items()) for b in BUILDS) + " |")
w("| HF7 export / import round trip | " + " | ".join("holds" if BS[b]["full"]["H_round_trip"]["holds"] else "fails" for b in BUILDS) + " |\n")

w("## Screens: silent differing units by program (untagged)\n")
progs = list(S["r2"]["H_core_screens"]["silent_by_program"])
w("| program | " + " | ".join(BUILDS) + " |\n|---|" + "---|" * len(BUILDS))
for p in progs:
    w(f"| {p} | " + " | ".join(str(S[b]["H_core_screens"]["silent_by_program"].get(p, "absent")) for b in BUILDS) + " |")
w("| pooled screen units equal, untagged | " + " | ".join(pct(S[b]["pooled"]["screen_untagged"]["equal"], S[b]["pooled"]["screen_untagged"]["units"]) for b in BUILDS) + " |")
w("| pooled file units equal, untagged | " + " | ".join(pct(S[b]["pooled"]["file_untagged"]["equal"], S[b]["pooled"]["file_untagged"]["units"]) for b in BUILDS) + " |")
w("| R-CEE-PIC8 column (equal/units) | " + " | ".join(pct(*S[b]["columns"]["pic8"]) for b in BUILDS) + " |\n")

w("## Batch: added programs (equal / units)\n")
bprogs = sorted({p for b in BUILDS for p in BS[b]["full"]["by_program"]})
w("| program | " + " | ".join(BUILDS) + " |\n|---|" + "---|" * len(BUILDS))
for p in bprogs:
    w(f"| {p} | " + " | ".join(
        pct(BS[b]["full"]["by_program"][p]["equal"], BS[b]["full"]["by_program"][p]["units"]) if p in BS[b]["full"]["by_program"] else "absent"
        for b in BUILDS) + " |")
w("")
w("## Batch: core steps, strict equivalence on the five sets (base, c01–c04)\n")
w("| step | " + " | ".join(BUILDS) + " |\n|---|" + "---|" * len(BUILDS))
for st in ["posttran", "intcalc", "creastmt", "tranrept"]:
    cells = []
    for b in BUILDS:
        v = [BS[b].get(f"{st}:{s}", {}).get("equivalence_strict") for s in ["base", "c01", "c02", "c03", "c04"]]
        cells.append(" / ".join("absent" if x is None else f"{x:.4g}" for x in v))
    w(f"| {st} | " + " | ".join(cells) + " |")
w("")

if any(UI11.values()):
    w("## Post-hoc sensitivity, decides nothing: browser cases with FIX11=1\n")
    w("Same 9 cases and the same browser plan as the registered run, rerun with the switch from LAB_NOTEBOOK §126. "
      "The registered HF5 result above stands.\n")
    w("| | " + " | ".join(BUILDS) + " |\n|---|" + "---|" * len(BUILDS))
    w("| steps ok, registered | " + " | ".join(UI[b]["steps_ok"] for b in BUILDS) + " |")
    w("| steps ok, FIX11=1 | " + " | ".join(UI11[b]["steps_ok"] if UI11[b] else "not run" for b in BUILDS) + " |")
    w("| cases all ok, registered | " + " | ".join(f"{sum(UI[b]['cases_all_steps_ok'].values())} of 9" for b in BUILDS) + " |")
    w("| cases all ok, FIX11=1 | " + " | ".join(f"{sum(UI11[b]['cases_all_steps_ok'].values())} of 9" if UI11[b] else "not run" for b in BUILDS) + " |")
